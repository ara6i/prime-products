export function validateProducts(products = SHOP_PRODUCTS) {
  const errors = [];
  const slugs = new Set();
  for (const product of products) {
    if (slugs.has(product.slug)) errors.push(`Duplicate slug: ${product.slug}`);
    slugs.add(product.slug);
    if (!product.sizes?.length) errors.push(`Missing sizes: ${product.slug}`);
    if (!PRODUCT_TYPES.includes(product.type)) {
      errors.push(`Invalid type ${product.type}: ${product.slug}`);
    }
    if (/\b(?:neon|electric|acid|bright yellow|bright orange)\b/i.test(product.color)) {
      errors.push(`Over-saturated color direction: ${product.slug}`);
    }
    if (/\b(?:black|navy)\b/i.test(product.color)) {
      errors.push(`Disallowed primary color: ${product.slug}`);
    }
  }
  for (const gender of ["women", "men"]) {
    const genderProducts = products.filter((product) => product.gender === gender);
    if (genderProducts.length !== 10) {
      errors.push(`${gender} must have 10 products, found ${genderProducts.length}`);
    }
    for (const type of PRODUCT_TYPES) {
      const count = genderProducts.filter((product) => product.type === type).length;
      if (count !== 2) errors.push(`${gender}/${type} must have 2 products, found ${count}`);
    }
  }
  if (errors.length) throw new Error(errors.join("\n"));
  return true;
}
