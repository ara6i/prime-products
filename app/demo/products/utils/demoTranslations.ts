function applyReplacements(value: string, replacements?: Record<string, string | number>): string {
  if (!replacements) return value;
  return Object.entries(replacements).reduce(
    (nextValue, [key, replacement]) => nextValue.replaceAll(`{${key}}`, String(replacement)),
    value,
  );
}

function fallbackFitTypeLabel(fitType: string): string {
  return fitType.replace(/-/g, " ").replace(/\b\w/g, (char) => char.toUpperCase());
}

function normalizeTerm(value: string): string {
  return value.trim().toLowerCase().replace(/\s+/g, " ");
}

export function useDemoTranslation() {
  const { language, setLanguage } = useLandingLanguage();
  const bundle = DEMO_TRANSLATIONS[language] ?? DEMO_TRANSLATIONS.en;

  return useMemo(() => {
    const translateDemo = (key: DemoTranslationKey, replacements?: Record<string, string | number>) => {
      const value = bundle.strings[key] ?? DEMO_TRANSLATIONS.en.strings[key] ?? key;
      return applyReplacements(value, replacements);
    };

    const translateDemoGroup = (id: DemoProductGroupId) => bundle.groups[id] ?? DEMO_TRANSLATIONS.en.groups[id];

    const translateDemoFitType = (fitType: string) => (
      bundle.fitTypes[fitType] ?? DEMO_TRANSLATIONS.en.fitTypes[fitType] ?? fallbackFitTypeLabel(fitType)
    );

    const translateDemoTerm = (value: string) => {
      const key = normalizeTerm(value);
      return bundle.terms[key] ?? DEMO_TRANSLATIONS.en.terms[key] ?? value;
    };

    return {
      language,
      setLanguage,
      translateDemo,
      translateDemoFitType,
      translateDemoGroup,
      translateDemoTerm,
    };
  }, [bundle, language, setLanguage]);
}
